"""Pre-rasterise Inter (SIL OFL) into crisp 1-bit glyphs for the TickrMeter renderer.

Run once at build time:  python3 tools/build_font_atlas.py
Writes market-face/font-atlas.cjs, so the Node renderer needs no font files,
canvas library or npm packages at runtime.
"""
import json
import os
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'market-face', 'font-atlas.cjs')
INTER = '/usr/share/fonts/opentype/inter/'

FAMILIES = {
    # Large numerals: price, clock, % change.
    'display': (INTER + 'InterDisplay-Bold.otf', [84, 80, 76, 72, 68, 64, 58, 52, 46, 42, 40, 38, 36, 34, 32, 30, 28, 26, 24]),
    # Labels, ticker, dates, highs/lows.
    'text': (INTER + 'Inter-Bold.otf', [28, 26, 24, 22, 21, 20, 19, 18, 17, 16, 15, 14, 13, 12, 11]),
}
CHARS = " 0123456789:.,$%+-−/·'&!()ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def glyph(font, ch):
    # Tabular figures keep the clock and prices from jittering sideways.
    mask = font.getmask(ch, mode='1', anchor='ls', features=['tnum'])
    x0, y0, x1, y1 = font.getbbox(ch, mode='1', anchor='ls', features=['tnum'])
    w, h = mask.size
    rows = []
    for y in range(h):
        bits = ''.join('1' if mask.getpixel((x, y)) else '0' for x in range(w))
        rows.append(format(int(bits, 2), 'x') if w else '0')
    adv = round(font.getlength(ch, features=['tnum']))
    return {'a': adv, 'x': x0, 'y': y0, 'w': w, 'h': h, 'r': rows}


atlas = {}
for family, (path, sizes) in FAMILIES.items():
    atlas[family] = {}
    for size in sizes:
        font = ImageFont.truetype(path, size)
        glyphs = {ch: glyph(font, ch) for ch in CHARS}
        cap = font.getbbox('H', mode='1', anchor='ls')
        atlas[family][size] = {'cap': -cap[1], 'g': glyphs}

with open(OUT, 'w') as f:
    f.write("'use strict';\n// Generated by tools/build_font_atlas.py from Inter Bold / Inter Display Bold\n")
    f.write("// (SIL Open Font License 1.1, https://rsms.me/inter). Do not edit by hand.\n")
    f.write('module.exports = ' + json.dumps(atlas, separators=(',', ':')) + ';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes')
