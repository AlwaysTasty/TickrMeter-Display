"""Convert a logo image into the 1-bit mask drawn (in white) on the black ticker bar.

Usage:
  python3 tools/convert_logo.py path/to/logo.png [--size 60] [--style auto|silhouette|detail]
                                [--dither] [--threshold 128] [--invert]

auto        Transparent logos become a solid silhouette; logos on a solid
            background keep their dark/coloured parts as ink.
silhouette  Every opaque (or non-background) pixel becomes white.
detail      Only dark or saturated pixels become white, keeping inner details.
--dither    Floyd-Steinberg dithering instead of a hard cut-off (photos, gradients).
--invert    Swap ink and background if the result looks reversed.

Writes market-face/logo.cjs and market-face/logo-preview.png (shown on black).
"""
import argparse
import colorsys
import json
import os
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
FACE = os.path.join(HERE, '..', 'market-face')

ap = argparse.ArgumentParser()
ap.add_argument('image')
ap.add_argument('--max-width', type=int, default=60, help='bar fits about 62 px wide')
ap.add_argument('--max-height', type=int, default=68, help='leave room for the session label')
ap.add_argument('--crop', help='x0,y0,x1,y1 in source pixels, e.g. to keep only a symbol')
ap.add_argument('--style', choices=['auto', 'silhouette', 'detail'], default='auto')
ap.add_argument('--dither', action='store_true')
ap.add_argument('--threshold', type=int, default=128)
ap.add_argument('--invert', action='store_true')
ap.add_argument('--out', default=os.path.join(FACE, 'logo.cjs'))
args = ap.parse_args()

src = Image.open(args.image)
src.seek(0)  # first frame of an animated file
rgba = src.convert('RGBA')
if args.crop:
    rgba = rgba.crop(tuple(int(v) for v in args.crop.split(',')))
w, h = rgba.size
px = rgba.load()

has_alpha = any(px[x, y][3] < 200 for x in range(0, w, max(1, w // 64)) for y in range(0, h, max(1, h // 64)))
corners = [px[0, 0], px[w - 1, 0], px[0, h - 1], px[w - 1, h - 1]]
bg = tuple(sorted(c[i] for c in corners)[1] for i in range(3))  # robust corner colour

style = args.style
if style == 'auto':
    style = 'silhouette' if has_alpha else 'detail'

ink = Image.new('L', (w, h), 0)
ip = ink.load()
for y in range(h):
    for x in range(w):
        r, g, b, a = px[x, y]
        if a < 40:
            continue
        if style == 'silhouette':
            if has_alpha:
                v = a
            else:  # distance from background colour
                d = max(abs(r - bg[0]), abs(g - bg[1]), abs(b - bg[2]))
                v = 255 if d > 48 else 0
        else:
            lum = 0.299 * r + 0.587 * g + 0.114 * b
            sat = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)[1]
            bg_lum = 0.299 * bg[0] + 0.587 * bg[1] + 0.114 * bg[2]
            darkness = 255 - lum if bg_lum > 128 else lum  # ink contrasts with background
            v = max(darkness, sat * 255 if sat > 0.3 else 0)
            v = int(v * a / 255)
        ip[x, y] = int(v)

if args.invert:
    ink = ImageOps.invert(ink)

box = ink.point(lambda v: 255 if v > 40 else 0).getbbox()
if not box:
    raise SystemExit('Nothing visible to convert; try --style silhouette or --invert.')
ink = ink.crop(box)
scale = min(args.max_width / ink.width, args.max_height / ink.height)
ink = ink.resize((max(1, round(ink.width * scale)), max(1, round(ink.height * scale))), Image.LANCZOS)

if args.dither:
    mono = ink.convert('1')  # Floyd-Steinberg
else:
    mono = ink.point(lambda v: 255 if v >= args.threshold else 0).convert('1', dither=Image.Dither.NONE)

mw, mh = mono.size
mp = mono.load()
rows = []
for y in range(mh):
    bits = ''.join('1' if mp[x, y] else '0' for x in range(mw))
    rows.append(format(int(bits, 2), 'x'))

with open(args.out, 'w') as f:
    f.write("'use strict';\n// Generated by tools/convert_logo.py. 1 = white pixel on the black bar.\n")
    f.write('module.exports = ' + json.dumps({'w': mw, 'h': mh, 'r': rows}) + ';\n')

preview = Image.new('L', (mw + 16, mh + 16), 0)
preview.paste(mono.convert('L'), (8, 8))
preview.resize((preview.width * 4, preview.height * 4), Image.NEAREST).save(args.out.replace('.cjs', '-preview.png'))
print(f'logo {mw}x{mh} ({style}{", dithered" if args.dither else ""}) -> {args.out}')
