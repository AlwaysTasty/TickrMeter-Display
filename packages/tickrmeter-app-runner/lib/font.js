const GLYPHS = Object.freeze(Object.fromEntries(Object.entries(rows).map(([letter, glyph]) =>
  [letter, Object.freeze({ width: glyph[0].length, rows: Object.freeze(glyph) })])));

function normalizeText(value) {
  return value.replace(/[æÆ]/gu, 'AE').replace(/[øØ]/gu, 'O').replace(/[œŒ]/gu, 'OE')
    .replace(/[łŁ]/gu, 'L').replace(/[ðÐ]/gu, 'D').replace(/[þÞ]/gu, 'TH')
    .replace(/ß/gu, 'SS').replace(/[‘’]/gu, "'").replace(/[“”]/gu, '"')
    .replace(/[–—−]/gu, '-').replace(/…/gu, '...').replace(/[·•]/gu, '.')
    .normalize('NFKD').replace(/\p{M}/gu, '').toUpperCase().replace(/\s+/gu, ' ').trim();
}

function measureText(value, scale) {
  return value.length ? ([...value].reduce((width, letter) => width + GLYPHS[letter].width + 1, 0) - 1) * scale : 0;
}

module.exports = { GLYPHS, normalizeText, measureText };
